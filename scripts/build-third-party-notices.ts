#!/usr/bin/env bun
/**
 * Writes THIRD_PARTY_NOTICES.md: the copyright and licence notice of every npm
 * package that the committed `dist/` bundles inline. MIT, ISC and BSD licences
 * require their notice in every copy, and the bundler drops it, so this file
 * carries the notices in the repository and the release tarball.
 *
 * Run after `bun run build`, with dependencies installed:
 *
 *   bun scripts/build-third-party-notices.ts
 *
 * test/third-party-notices.test.ts fails when `dist/` bundles a package this
 * file does not cover. Vocabulary data has its own notices
 * (docs/THIRD_PARTY_DATA.md); models and tools that the user's computer
 * downloads are not bundled and are not listed here.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const BUNDLED_OUTPUTS = [
  'dist/index.js',
  'dist/cli.js',
  'dist/embedding-drain.js',
  'dist/litert-helper.js',
  'dist/control-ui/index.js',
] as const;

export const NOTICES_FILE = 'THIRD_PARTY_NOTICES.md';

/** Bun marks each inlined module with a `// node_modules/<package>/<file>` comment. */
const MODULE_MARKER = /^\/\/ node_modules\/((?:@[^/\s]+\/)?[^/\s]+)\//gm;

export function bundledPackages(root: string): string[] {
  const names = new Set<string>();
  for (const output of BUNDLED_OUTPUTS) {
    const path = join(root, output);
    if (!existsSync(path)) continue;
    for (const match of readFileSync(path, 'utf8').matchAll(MODULE_MARKER)) names.add(match[1]!);
  }
  return [...names].sort();
}

/** The `## <package> <version>` headings in a notices file. */
export function noticedPackages(notices: string): string[] {
  return [...notices.matchAll(/^## (\S+) \S+$/gm)].map((match) => match[1]!);
}

function licenceFile(dir: string): string | undefined {
  const name = readdirSync(dir).find((entry) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(entry));
  return name ? readFileSync(join(dir, name), 'utf8').trim() : undefined;
}

function declaredLicence(manifest: Record<string, unknown>): string {
  const licence = manifest.license;
  if (typeof licence === 'string') return licence;
  if (licence && typeof licence === 'object' && typeof (licence as { type?: unknown }).type === 'string') return (licence as { type: string }).type;
  return 'not declared';
}

function author(manifest: Record<string, unknown>): string | undefined {
  const value = manifest.author;
  if (typeof value === 'string') return value;
  if (value && typeof value === 'object' && typeof (value as { name?: unknown }).name === 'string') return (value as { name: string }).name;
  return undefined;
}

export function renderNotices(root: string): string {
  const sections = bundledPackages(root).map((name) => {
    const dir = join(root, 'node_modules', name);
    const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')) as Record<string, unknown>;
    const licence = declaredLicence(manifest);
    const text = licenceFile(dir)
      ?? `The package includes no licence file. Its package.json declares the ${licence} licence${author(manifest) ? `, author ${author(manifest)}` : ''}.`;
    return [
      `## ${name} ${String(manifest.version)}`,
      '',
      `Licence: ${licence}. Source: https://www.npmjs.com/package/${name}`,
      '',
      '```text',
      text,
      '```',
    ].join('\n');
  });
  return [
    '# Third-party notices',
    '',
    'Olympus is licensed under the MIT License (see LICENSE). Its built files in',
    '`dist/` include code from the npm packages below. Each is used under its own',
    'licence, reproduced here as that licence requires. Generated by',
    '`scripts/build-third-party-notices.ts`; do not edit by hand.',
    '',
    'Data files carry their own notices: see docs/THIRD_PARTY_DATA.md.',
    '',
    ...sections.flatMap((section) => [section, '']),
  ].join('\n');
}

if (import.meta.main) {
  const root = process.cwd();
  if (process.argv.includes('--stdout')) process.stdout.write(renderNotices(root));
  else writeFileSync(join(root, NOTICES_FILE), renderNotices(root));
}
