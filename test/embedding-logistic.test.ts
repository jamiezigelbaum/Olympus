import { expect, test } from 'bun:test';
import { trainLogistic, trainLogisticSteps, privateProbability, EMBEDDING_PREFILTER_DIMENSIONS as D } from '../src/workers/classification/embedding-logistic.ts';
const vector = (sign: number) => [sign, ...new Array(D - 1).fill(0)];
test('minimum applies to each valid class, and invalid vectors never train', () => {
  expect(trainLogistic([{ vector: vector(1), private: false }])).toBeUndefined();
  expect(trainLogistic([{ vector: vector(1), private: false }, { vector: [], private: true }], 1)).toBeUndefined();
});
test('synthetic separable classes yield low and high Private probabilities', () => {
  const examples = Array.from({ length: 200 }, (_, index) => ({ vector: vector(index % 2 ? 1 : -1), private: index % 2 === 1 }));
  const model = trainLogistic(examples, 50)!;
  expect(privateProbability(model, vector(-1))!).toBeLessThan(0.01);
  expect(privateProbability(model, vector(1))!).toBeGreaterThan(0.99);
  expect(privateProbability(model, [NaN, ...vector(1).slice(1)])).toBeUndefined();
  expect(privateProbability(model, new Array(D).fill(0))).toBeUndefined();
  expect(privateProbability({ weights: [], bias: 0 }, vector(1))).toBeUndefined();
});
test('balanced loss gives confident symmetric scores despite 19:1 class imbalance', () => {
  const examples = Array.from({ length: 200 }, (_, i) => ({ vector: vector(i < 190 ? -1 : 1), private: i >= 190 }));
  const model = trainLogistic(examples, 1)!;
  expect(privateProbability(model, vector(-1))!).toBeLessThan(0.01);
  expect(privateProbability(model, vector(1))!).toBeGreaterThan(0.99);
  expect(model.bias).toBeCloseTo(0, 6);
});
test('matches an independent C=10 balanced-loss reference with an unpenalized intercept', () => {
  // Reference generated once with Python 3, Newton's method on the ORIGINAL
  // summed objective (not the fitter's scaled objective or L-BFGS algorithm):
  // import math
  // rows = [(-1,0)]*3 + [(1,0)] + [(-1,1)] + [(1,1)]*2
  // w = b = 0.
  // for _ in range(30):
  //     gw, gb, hww, hwb, hbb = w, 0., 1., 0., 0.
  //     for x,y in rows:
  //         a = 10*len(rows)/(2*sum(t == y for _,t in rows))
  //         p = 1/(1+math.exp(-(w*x+b)))
  //         e, h = a*(p-y), a*p*(1-p)
  //         gw += e*x; gb += e
  //         hww += h*x*x; hwb += h*x; hbb += h
  //     det = hww*hbb-hwb*hwb
  //     dw, db = (hbb*gw-hwb*gb)/det, (hww*gb-hwb*gw)/det
  //     w -= dw; b -= db
  //     if max(abs(gw),abs(gb)) < 1e-13: break
  // print(repr(w), repr(b))
  const rows = [[-1, false], [-1, false], [-1, false], [1, false], [-1, true], [1, true], [1, true]] as const;
  const model = trainLogistic(rows.map(([x, label]) => ({ vector: vector(x), private: label })), 1)!;
  expect(model.weights[0]).toBeCloseTo(0.8377611409585523, 6);
  expect(model.bias).toBeCloseTo(0.07819149191797578, 6);
  expect(model.weights.slice(1).every(w => w === 0)).toBe(true);
  expect(privateProbability(model, vector(-1))!).toBeCloseTo(0.3187397073532996, 7);
  expect(privateProbability(model, vector(1))!).toBeCloseTo(0.714216709491555, 7);
});
test('converges to a norm-85 solution on nearly parallel vectors using the last embedding coordinate', () => {
  const examples = Array.from({ length: 4000 }, (_, i) => {
    const input = new Array<number>(D).fill(0);
    input[0] = Math.sqrt(1 - 0.03 ** 2);
    input[D - 1] = i % 2 ? 0.03 : -0.03;
    return { vector: input, private: i % 2 === 1 };
  });
  // Symmetry gives b=w[0]=0; the original summed objective's scalar stationary
  // equation is w = C*N*.03/(1+exp(.03*w)). Reference generated by bisection:
  // import math
  // lo, hi = 0., 1200.
  // for _ in range(100):
  //     w = (lo+hi)/2
  //     if w > 1200/(1+math.exp(.03*w)): hi = w
  //     else: lo = w
  // print(repr((lo+hi)/2))
  const model = trainLogistic(examples)!;
  expect(model.weights[D - 1]).toBeCloseTo(85.56210007343344, 3);
  expect(Math.hypot(...model.weights)).toBeGreaterThan(80);
  expect(model.bias).toBeCloseTo(0, 6);
  expect(model.weights.slice(0, D - 1).every(w => Math.abs(w) < 1e-6)).toBe(true);
});
test('fit yields during optimization and is identical across pause/resume schedules', async () => {
  const examples = Array.from({ length: 200 }, (_, i) => ({ vector: vector(i % 2 ? 1 : -1), private: i % 2 === 1 }));
  const fit = trainLogisticSteps(examples, 1);
  let yields = 0, step = fit.next();
  while (!step.done) {
    expect(step.value).toBeUndefined();
    yields++;
    if (yields % 31 === 0) await Promise.resolve();
    step = fit.next();
  }
  // Input normalization alone must not be the only cooperative phase.
  expect(yields).toBeGreaterThan(2 * examples.length);
  expect(yields).toBeLessThan(1_000_000);
  expect(step.value).toEqual(trainLogistic(examples, 1));
});
